const preference = "ar-guide-language";
export const isHostPC = location.protocol === "http:" && ["127.0.0.1", "localhost"].includes(location.hostname);
const selector = document.getElementById("locale");
export let language = "ja";
try {
  if (localStorage.getItem(preference) === "en") language = "en";
} catch { /* The switch also works without browser storage. */ }

export function t(source) {
  if (language === "ja") return source;
  if (Object.hasOwn(english, source)) return english[source];
  // A model build error can include a diagnostic after the translated message.
  const prefix = "モデルの形状・動作の組立に失敗しました。";
  return source.startsWith(prefix) ? english[prefix] + source.slice(prefix.length) : source;
}

const labels = new WeakMap();

function draw(node, property, {source, values}) {
  const text = t(source).replace(/\{(\w+)\}/g, (match, key) => values[key] ?? match);
  if (property === "textContent") node.textContent = text;
  else node.setAttribute(property, text);
}

export function ui(node, source, values = {}, property = "textContent") {
  if (!labels.has(node)) {
    labels.set(node, new Map());
    node.dataset.localized = "";
  }
  const label = {source, values};
  labels.get(node).set(property, label);
  draw(node, property, label);
}

for (const node of document.querySelectorAll("[data-ui]")) ui(node, node.textContent);
for (const property of ["aria-label", "title", "alt"]) {
  for (const node of document.querySelectorAll("[" + property + "]")) {
    const source = node.getAttribute(property);
    if (Object.hasOwn(english, source)) ui(node, source, {}, property);
  }
}

function selectLanguage() {
  document.documentElement.lang = language;
  selector.value = language;
}
selectLanguage();
function changeLanguage(value) {
  if (value === language) return;
  language = value;
  selectLanguage();
  for (const node of document.querySelectorAll("[data-localized]")) {
    for (const [property, label] of labels.get(node)) draw(node, property, label);
  }
  document.dispatchEvent(new Event("guide-language-change"));
}
selector.onchange = () => {
  changeLanguage(selector.value);
  try { localStorage.setItem(preference, language); } catch {}
};

function restoreLanguage() {
  try { changeLanguage(localStorage.getItem(preference) === "en" ? "en" : "ja"); } catch {}
}
window.addEventListener("pageshow", event => { if (event.persisted) restoreLanguage(); });
window.addEventListener("storage", event => {
  if (event.key === preference || event.key === null) restoreLanguage();
});
